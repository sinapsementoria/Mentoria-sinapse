// Regras de sufixo: padrão sem acento → com acento
const _REGRAS_SUFIXO = [
  // -CAO → -ÇÃO (ex: EDUCACAO → EDUCAÇÃO)
  [/^([A-Z]+)CAO$/, function(m,p){ return p + "ÇÃO"; }],
  [/^([A-Z]+)CAOS$/, function(m,p){ return p + "ÇÕES"; }],
  [/^([A-Z]+)COES$/, function(m,p){ return p + "ÇÕES"; }],
  // -SAO → -SÃO (quando não está no dicionário)
  // -DAO → -DÃO
  [/^([A-Z]+[^AEIOU])DAO$/, function(m,p){ return p + "DÃO"; }],
  // -NCIA → -NCIA (sem mudança, mas -NCIA sem acento precede)
  // -ENCIA → -ÊNCIA
  [/^([A-Z]+)ENCIA$/, function(m,p){ return p + "ÊNCIA"; }],
  [/^([A-Z]+)ENCIAS$/, function(m,p){ return p + "ÊNCIAS"; }],
  // -ANCIA → -ÂNCIA
  [/^([A-Z]+)ANCIA$/, function(m,p){ return p + "ÂNCIA"; }],
  [/^([A-Z]+)ANCIAS$/, function(m,p){ return p + "ÂNCIAS"; }],
  // -ICO → -ICO (proparoxítonas em -ICO)
  // Handled by dictionary mostly
  // -ICA → proparoxítonas
  // -OGIA → ok sem acento
  // -VEL → -VEL (paroxítonas)
  [/^([A-Z]+)AVEL$/, function(m,p){ return p + "ÁVEL"; }],
  [/^([A-Z]+)IVEL$/, function(m,p){ return p + "ÍVEL"; }],
  [/^([A-Z]+)OVEL$/, function(m,p){ return p + "ÓVEL"; }],
  // -ORIO → -ÓRIO
  [/^([A-Z]+)ORIO$/, function(m,p){ return p + "ÓRIO"; }],
  [/^([A-Z]+)ORIA$/, function(m,p){ 
    // Exceções: HISTORIA→HISTÓRIA, MEMORIA→MEMÓRIA
    var full = p + "ÓRIA";
    // Mas CATEGORIA, ALEGORIA não levam acento
    if (/^(CATEG|ALEG)/.test(p)) return m;
    return full;
  }],
];

/**
 * Corrige acentuação de uma única palavra
 */
function _corrigirPalavra(palavra) {
  var upper = palavra.toUpperCase();
  
  // Proteger siglas
  if (_SIGLAS_PROTEGIDAS.has(upper)) return upper;
  
  // Proteger números e fórmulas
  if (/\d/.test(palavra)) return upper;
  if (upper.length <= 1) return upper;
  
  // Busca direta no dicionário
  if (_DICIONARIO[upper]) return _DICIONARIO[upper];
  
  // Aplicar regras de sufixo
  for (var i = 0; i < _REGRAS_SUFIXO.length; i++) {
    var regra = _REGRAS_SUFIXO[i];
    if (regra[0].test(upper)) {
      var resultado = upper.replace(regra[0], regra[1]);
      if (resultado !== upper) return resultado;
    }
  }
  
  return upper;
}

/**
 * Função global de correção textual
 * Corrige acentuação de um texto completo
 */
function corrigirAcentuacao(texto) {
  if (!texto) return texto;
  // Limpa espaços duplicados e trim
  texto = texto.replace(/\s+/g, ' ').trim();
  
  return texto.split(' ').map(function(p) {
    if (!p) return p;
    return _corrigirPalavra(p);
  }).join(' ');
}

// Alias global
var corrigirTextoBrasileiro = corrigirAcentuacao;

// ═══════════════════════════════════════════════════════
// AUTO-APLICAÇÃO GLOBAL em todos os inputs e textareas
// ═══════════════════════════════════════════════════════
document.addEventListener('DOMContentLoaded', function() {
  document.addEventListener('focusout', function(e) {
    var el = e.target;
    if (!el) return;
    var tag = el.tagName;
    if (tag !== 'INPUT' && tag !== 'TEXTAREA') return;
    if (el.type && el.type !== 'text' && el.type !== 'search' && tag !== 'TEXTAREA') return;
    if (el.readOnly || el.disabled) return;
    // Não corrigir campos de senha, email, url, date
    if (['password','email','url','date','number'].indexOf(el.type) >= 0) return;
    
    if (el.value && el.value.trim()) {
      el.value = corrigirAcentuacao(el.value);
    }
  });
});
