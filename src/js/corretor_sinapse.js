function aplicarCorrecao(el) {
  if (!el || !el.value || !el.value.trim()) return;
  var tag = el.tagName;
  if (tag !== "INPUT" && tag !== "TEXTAREA") return;
  var tipo = (el.type || "text").toLowerCase();
  if (["password","email","url","date","number","hidden","color","range","file"].indexOf(tipo) >= 0) return;
  if (el.readOnly || el.disabled) return;
  
  el.value = window.corrigirTextoBrasileiro(el.value);
}

// Correção em tempo real: ao digitar espaço, corrige a palavra anterior
function correcaoTempoReal(el) {
  if (!el || !el.value) return;
  var tag = el.tagName;
  if (tag !== "INPUT" && tag !== "TEXTAREA") return;
  var tipo = (el.type || "text").toLowerCase();
  if (["password","email","url","date","number","hidden","color","range","file"].indexOf(tipo) >= 0) return;
  if (el.readOnly || el.disabled) return;
  
  var val = el.value;
  // Se termina com espaço, corrige tudo que veio antes
  if (val.length > 0 && val[val.length - 1] === " ") {
    var cursorPos = el.selectionStart;
    var partes = val.trimEnd().split(" ");
    var corrigidas = partes.map(function(p) {
      if (!p) return p;
      return corrigirPalavra(p.toUpperCase() === p ? p : p);
    });
    var novo = corrigidas.join(" ") + " ";
    if (novo !== val) {
      el.value = novo;
      // Reposicionar cursor
      var diff = novo.length - val.length;
      el.setSelectionRange(cursorPos + diff, cursorPos + diff);
    }
  }
}

document.addEventListener("DOMContentLoaded", function() {
  // ▶ CORREÇÃO INSTANTÂNEA ao digitar (a cada espaço)
  document.addEventListener("input", function(e) {
    correcaoTempoReal(e.target);
  }, true);
  
  // ▶ Correção completa ao sair do campo
  document.addEventListener("focusout", function(e) {
    aplicarCorrecao(e.target);
  }, true);
  
  // ▶ Correção ao pressionar Enter
  document.addEventListener("keydown", function(e) {
    if (e.key === "Enter") {
      aplicarCorrecao(e.target);
    }
  }, true);
});

