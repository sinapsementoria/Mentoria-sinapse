function corrigirPalavra(p) {
  var u = p.toUpperCase();
  
  // Proteger siglas
  if (_sigSet[u]) return u;
  
  // Proteger números e fórmulas
  if (/\d/.test(p)) return u;
  if (u.length <= 1) return u;
  
  // Busca no dicionário
  if (DIC[u]) return DIC[u];
  
  // Aplicar regras de sufixo
  for (var i = 0; i < REGRAS.length; i++) {
    if (REGRAS[i][0].test(u)) {
      var res = u.replace(REGRAS[i][0], REGRAS[i][1]);
      if (res !== u) return res;
    }
  }
  
  return u;
}

// Função global principal
window.corrigirTextoBrasileiro = function(texto, options) {
  if (!texto) return texto;
  options = options || {};
  
  // Limpar espaços
  texto = texto.replace(/\s+/g, " ").trim();
  
  var resultado = texto.split(" ").map(function(p) {
    if (!p) return p;
    return corrigirPalavra(p);
  }).join(" ");
  
  if (options.caixaAlta) {
    resultado = resultado.toUpperCase();
  }
  
  return resultado;
};

